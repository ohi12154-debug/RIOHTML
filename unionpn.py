class fruit:


# Constructor

    def __init__(self, n1, col):

        self.name = n1
        self.color = col

# Object Creation
 
ob1 = fruit('momo', 'steme')
ob2 = fruit('ice-creame', 'chocolate')
ob3 = fruit('ramen','3x spicy')

# Calling Function

print(ob1.name)
print(ob1.color)
print(ob2.name)
print(ob2.color)
print(ob3.name)
print(ob3.color)